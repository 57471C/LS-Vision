// Finds the local OpenCV SDK and Clang, then runs the Tauri CLI.
// Cargo's opencv build script exits if those paths are missing from the environment.
// This writes .cargo/config.toml so a later cargo build in this repo sees them too.

import { execFileSync, spawn } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tauriCli = path.join(root, "node_modules", "@tauri-apps", "cli", "tauri.js");

function slash(value) {
	return value.replaceAll("\\", "/");
}

function toml(value) {
	return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

function newestDir(parent, childName) {
	if (!existsSync(parent)) return "";
	const found = readdirSync(parent, { withFileTypes: true })
		.filter((entry) => entry.isDirectory() && existsSync(path.join(parent, entry.name, childName)))
		.map((entry) => entry.name)
		.sort();
	if (found.length === 0) return "";
	return path.join(parent, found.at(-1), childName);
}

function worldLibrary() {
	const fromEnv = process.env.OPENCV_LINK_PATHS?.split(",")[0]?.trim();
	const candidates = [
		fromEnv,
		"C:\\tools\\opencv\\build\\x64\\vc17\\lib",
		"C:\\tools\\opencv\\build\\x64\\vc16\\lib",
		"C:\\opencv\\build\\x64\\vc17\\lib",
		"C:\\opencv\\build\\x64\\vc16\\lib",
	].filter(Boolean);
	for (const dir of candidates) {
		if (!existsSync(dir)) continue;
		const libs = readdirSync(dir)
			.filter((name) => /^opencv_world\d+\.lib$/i.test(name))
			.sort();
		const file = libs.at(-1);
		if (!file) continue;
		const include =
			process.env.OPENCV_INCLUDE_PATHS?.split(",")[0]?.trim() ||
			path.resolve(dir, "../../../include");
		if (!existsSync(path.join(include, "opencv2", "core", "version.hpp"))) continue;
		return {
			libDir: dir,
			include,
			name: file.replace(/\.lib$/i, ""),
		};
	}
	return null;
}

function clangBin() {
	const fromEnv = process.env.LIBCLANG_PATH?.trim();
	const candidates = [fromEnv, "C:\\Program Files\\LLVM\\bin"].filter(Boolean);
	return candidates.find((dir) => existsSync(path.join(dir, "libclang.dll"))) ?? "";
}

function msvcInclude() {
	const vswhere = "C:\\Program Files (x86)\\Microsoft Visual Studio\\Installer\\vswhere.exe";
	if (!existsSync(vswhere)) return "";
	let install = "";
	try {
		install = execFileSync(
			vswhere,
			[
				"-latest",
				"-products",
				"*",
				"-requires",
				"Microsoft.VisualStudio.Component.VC.Tools.x86.x64",
				"-property",
				"installationPath",
			],
			{ encoding: "utf8" },
		)
			.split(/\r?\n/)
			.map((line) => line.trim())
			.find(Boolean);
	} catch {
		return "";
	}
	if (!install) return "";
	return newestDir(path.join(install, "VC", "Tools", "MSVC"), "include");
}

function windowsIncludes() {
	const kit = newestDir("C:\\Program Files (x86)\\Windows Kits\\10\\Include", "ucrt");
	if (!kit) return [];
	const root = path.dirname(kit);
	return ["ucrt", "shared", "um"]
		.map((name) => path.join(root, name))
		.filter((dir) => existsSync(dir));
}

function clangArgs(includes) {
	if (process.env.OPENCV_CLANG_ARGS?.trim()) return process.env.OPENCV_CLANG_ARGS.trim();
	const args = ["--target=x86_64-pc-windows-msvc"];
	for (const include of includes) args.push(`-isystem "${slash(include)}"`);
	return args.join(" ");
}

function configureWindows() {
	const world = worldLibrary();
	const clang = clangBin();
	const msvc = msvcInclude();
	const kits = windowsIncludes();
	const missing = [];
	if (!world) missing.push("OpenCV SDK (opencv_world*.lib and build/include)");
	if (!clang) missing.push("LLVM (libclang.dll)");
	if (!msvc) missing.push("MSVC C++ headers");
	if (kits.length < 3) missing.push("Windows SDK headers");
	if (missing.length > 0) {
		console.error(`Cannot build the OpenCV caliper. Missing: ${missing.join(", ")}.`);
		process.exit(1);
	}
	const env = {
		OPENCV_LINK_LIBS: process.env.OPENCV_LINK_LIBS?.trim() || world.name,
		OPENCV_LINK_PATHS: slash(world.libDir),
		OPENCV_INCLUDE_PATHS: slash(world.include),
		LIBCLANG_PATH: slash(clang),
		// clang-sys wants the executable, not the directory. PATH is left alone
		// because Cargo replaces it instead of prepending.
		CLANG_PATH: slash(path.join(clang, "clang.exe")),
		OPENCV_DISABLE_PROBES: "pkg_config,cmake,vcpkg_cmake,vcpkg",
		OPENCV_CLANG_ARGS: clangArgs([msvc, ...kits]),
	};
	const cargoDir = path.join(root, ".cargo");
	mkdirSync(cargoDir, { recursive: true });
	const body = ["# Generated by scripts/tauri.mjs. Machine-local. Do not commit.", "[env]"];
	for (const [key, value] of Object.entries(env)) {
		body.push(`${key} = ${toml(value)}`);
	}
	body.push("");
	writeFileSync(path.join(cargoDir, "config.toml"), body.join("\n"));
	return env;
}

const extra = process.platform === "win32" ? configureWindows() : {};
const child = spawn(process.execPath, [tauriCli, ...process.argv.slice(2)], {
	cwd: root,
	env: { ...process.env, ...extra },
	stdio: "inherit",
});
child.on("exit", (code, signal) => {
	if (signal) {
		process.kill(process.pid, signal);
		return;
	}
	process.exit(code ?? 1);
});
